#!/usr/bin/env node
// Builds dist/chrome/ and dist/firefox/ (+ zip packages) from the single src/ tree. Node built-ins only.
//
//   node build.mjs                      build both browsers and zip them
//   node build.mjs --target=firefox     one browser
//   node build.mjs --no-zip             skip packaging
//   node build.mjs --out=/tmp/out       alternative output directory

import { readFile, writeFile, mkdir, rm, readdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { TARGETS, buildManifest, validateManifest } from './scripts/lib/manifest.mjs';
import { bundle } from './scripts/lib/bundle.mjs';
import { createZip } from './scripts/lib/zip.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'src');
const CONTENT_ENTRIES = ['content/fill.js', 'content/capture.js'];

const EXCLUDE = {
  common: [/^manifest\.[a-z]+\.json$/, /^content\//, /^lib\/build-info\.js$/, /(^|\/)\.[^/]+$/],
  chrome: [],
  firefox: [/^offscreen\//],
};

const FORBIDDEN_IN_OUTPUT = [
  [/\.innerHTML\s*=/, 'innerHTML assignment'],
  [/\.outerHTML\s*=/, 'outerHTML assignment'],
  [/insertAdjacentHTML\s*\(/, 'insertAdjacentHTML'],
  [/document\.write\s*\(/, 'document.write'],
  [/\beval\s*\(/, 'eval'],
  [/\bnew\s+Function\s*\(/, 'new Function'],
  [/setTimeout\s*\(\s*['"`]/, 'string setTimeout'],
  [/\bimport\b[^;\n]*['"](?:https?:)?\/\//, 'remote module import'],
  [/\b(?:src|href)\s*=\s*["'](?:https?:)?\/\//i, 'remote resource reference'],
  [/importScripts\s*\(/, 'importScripts'],
  [/@import\s+url\(\s*['"]?(?:https?:)?\/\//i, 'remote stylesheet import'],
];

async function walk(dir, base = dir) {
  const out = [];
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...(await walk(full, base)));
    else if (ent.isFile()) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

function excluded(rel, target) {
  return [...EXCLUDE.common, ...EXCLUDE[target]].some((re) => re.test(rel));
}

/**
 * Scan built JS/HTML for forbidden constructs (defence in depth on top of the CSP).
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
export async function scanOutput(dir) {
  const problems = [];
  for (const rel of await walk(dir)) {
    if (!/\.(js|html|css)$/.test(rel)) continue;
    const text = await readFile(path.join(dir, rel), 'utf8');
    for (const [re, what] of FORBIDDEN_IN_OUTPUT) if (re.test(text)) problems.push(`${rel}: ${what}`);
    if (rel.endsWith('.html') && /<script(?![^>]*\ssrc=)[^>]*>/i.test(text)) problems.push(`${rel}: inline <script>`);
    if (rel.endsWith('.html') && /\son[a-z]+\s*=/i.test(text)) problems.push(`${rel}: inline event handler`);
    if (rel.endsWith('.html') && /\sstyle\s*=/i.test(text)) problems.push(`${rel}: inline style attribute`);
  }
  return problems;
}

/**
 * @param {{targets?: string[], outDir?: string, zip?: boolean, log?: (msg: string) => void}} [opts]
 */
export async function build({ targets = [...TARGETS], outDir = path.join(ROOT, 'dist'), zip = true, log = () => {} } = {}) {
  const pkg = JSON.parse(await readFile(path.join(ROOT, 'package.json'), 'utf8'));
  const version = pkg.version;
  const files = await walk(SRC);
  const results = [];
  for (const target of targets) {
    if (!TARGETS.includes(target)) throw new Error(`unknown target ${target}`);
    const dir = path.join(outDir, target);
    await rm(dir, { recursive: true, force: true });
    await mkdir(dir, { recursive: true });

    for (const rel of files) {
      if (excluded(rel, target)) continue;
      const dest = path.join(dir, rel);
      await mkdir(path.dirname(dest), { recursive: true });
      await copyFile(path.join(SRC, rel), dest);
    }
    await writeFile(
      path.join(dir, 'lib', 'build-info.js'),
      `// Generated by build.mjs — do not edit.\nexport const BUILD = Object.freeze(${JSON.stringify({ browser: target, version })});\n`,
    );
    for (const entry of CONTENT_ENTRIES) {
      const code = await bundle(path.join(SRC, entry), {
        root: SRC,
        banner: `// Ludworks Passwords ${version} — ${entry} (generated by build.mjs from src/; do not edit)\n`,
      });
      new vm.Script(code, { filename: entry }); // syntax check: must be a valid classic script
      const dest = path.join(dir, entry);
      await mkdir(path.dirname(dest), { recursive: true });
      await writeFile(dest, code);
    }
    const manifest = await buildManifest(SRC, target, version);
    await writeFile(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    const errors = await validateManifest(manifest, target, { dir });
    if (errors.length) throw new Error(`${target}: invalid manifest:\n  - ${errors.join('\n  - ')}`);
    const problems = await scanOutput(dir);
    if (problems.length) throw new Error(`${target}: forbidden constructs in output:\n  - ${problems.join('\n  - ')}`);

    let zipPath = null;
    if (zip) {
      const entries = [];
      for (const rel of await walk(dir)) entries.push({ name: rel, data: await readFile(path.join(dir, rel)) });
      zipPath = path.join(outDir, `ludworks-passwords-${target}-${version}.zip`);
      await writeFile(zipPath, createZip(entries));
    }
    log(`${target}: ${dir}${zipPath ? ` -> ${path.relative(ROOT, zipPath)}` : ''}`);
    results.push({ target, dir, zipPath, manifest });
  }
  return results;
}

async function main() {
  const args = process.argv.slice(2);
  const opt = (name) => {
    const a = args.find((x) => x.startsWith(`--${name}=`));
    return a ? a.slice(name.length + 3) : null;
  };
  const target = opt('target');
  await build({
    targets: target ? [target] : [...TARGETS],
    outDir: opt('out') ? path.resolve(opt('out')) : path.join(ROOT, 'dist'),
    zip: !args.includes('--no-zip'),
    log: (m) => console.log(m),
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((e) => {
    console.error(e.message || e);
    process.exit(1);
  });
}
