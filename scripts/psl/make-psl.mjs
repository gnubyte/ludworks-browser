#!/usr/bin/env node
// Compiles the vendored Public Suffix List snapshot (scripts/psl/public_suffix_list.dat, ICANN + PRIVATE
// sections) into src/lib/psl-data.js, the rule table used by src/lib/url-match.js. Node built-ins only; the
// build never touches the network, so the list is pinned by SHA-256 and refreshed deliberately:
//
//   1. download https://publicsuffix.org/list/public_suffix_list.dat over the snapshot below;
//   2. update PSL_SHA256 and PSL_VERSION here (the version is the list's publication date/time);
//   3. node scripts/psl/make-psl.mjs           (rewrites src/lib/psl-data.js)
//   4. node --test tests/psl.test.mjs tests/url-match.test.mjs
//
//   node scripts/psl/make-psl.mjs --check      exit 1 when psl-data.js is stale or was edited by hand
//
// Output format: one string of space-separated rules, in punycode (URL.hostname is always ASCII), sorted and
// de-duplicated. Rules keep their PSL syntax: "*.ck" (wildcard, leftmost label only) and "!www.ck"
// (exception).

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { domainToASCII, fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DAT_PATH = path.join(HERE, 'public_suffix_list.dat');
export const OUT_PATH = path.join(HERE, '..', '..', 'src', 'lib', 'psl-data.js');

/** Snapshot pinned by the build (Debian/Ubuntu package publicsuffix 20260129.1928-1 = upstream list of that date). */
export const PSL_VERSION = '2026-01-29T19:28Z';
export const PSL_SHA256 = 'f3604fee29f4a2234547ca068da1e4c6a1c480418f1c418d4b4040633be501b4';

function toAsciiLabel(label, rule) {
  if (label === '*') return label;
  if (/^[a-z0-9-]+$/.test(label)) return label;
  const a = domainToASCII(label);
  if (!a || a.includes('.') || !/^[a-z0-9-]+$/.test(a)) throw new Error(`PSL: cannot convert label "${label}" of rule "${rule}"`);
  return a;
}

/**
 * Parse the .dat text into sorted, de-duplicated punycode rules.
 * @param {string} text
 * @returns {{rules: string[], icann: number, private: number}}
 */
export function parseDat(text) {
  const out = new Set();
  let section = null;
  const counts = { icann: 0, private: 0 };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.includes('===BEGIN ICANN DOMAINS===')) section = 'icann';
    else if (line.includes('===BEGIN PRIVATE DOMAINS===')) section = 'private';
    else if (line.includes('===END ')) section = null;
    if (!line || line.startsWith('//')) continue;
    if (!section) throw new Error(`PSL: rule outside the ICANN/PRIVATE sections: "${line}"`);
    const token = line.split(/\s/)[0].toLowerCase();
    const exception = token.startsWith('!');
    const body = exception ? token.slice(1) : token;
    const labels = body.split('.');
    if (!body || labels.some((l) => l === '')) throw new Error(`PSL: malformed rule "${token}"`);
    if (labels.slice(1).includes('*') || (exception && labels[0] === '*')) throw new Error(`PSL: unsupported wildcard in "${token}"`);
    const ascii = labels.map((l) => toAsciiLabel(l, token)).join('.');
    out.add(exception ? `!${ascii}` : ascii);
    counts[section]++;
  }
  if (!counts.icann || !counts.private) throw new Error('PSL: ICANN or PRIVATE section missing');
  return { rules: [...out].sort(), icann: counts.icann, private: counts.private };
}

/**
 * Generated module text for a .dat snapshot (verified against the pinned hash).
 * @param {Buffer|string} dat
 */
export function generate(dat) {
  // The pinned hash is of the upstream file (LF line endings); a CRLF checkout must not change it.
  const buf = Buffer.from((Buffer.isBuffer(dat) ? dat.toString('utf8') : String(dat)).replace(/\r\n/g, '\n'), 'utf8');
  const sha = createHash('sha256').update(buf).digest('hex');
  if (sha !== PSL_SHA256) {
    throw new Error(`PSL: ${path.relative(process.cwd(), DAT_PATH)} has SHA-256 ${sha}, expected the pinned ${PSL_SHA256}. Update PSL_SHA256/PSL_VERSION in make-psl.mjs when refreshing the list.`);
  }
  const { rules, icann, private: priv } = parseDat(buf.toString('utf8'));
  for (const r of rules) if (!/^!?(?:\*\.)?[a-z0-9-]+(?:\.[a-z0-9-]+)*$/.test(r)) throw new Error(`PSL: unexpected rule "${r}"`);
  const info = { version: PSL_VERSION, sha256: PSL_SHA256, rules: rules.length, icann, private: priv };
  return [
    '// Generated by scripts/psl/make-psl.mjs from scripts/psl/public_suffix_list.dat — do not edit.',
    '// Public Suffix List (https://publicsuffix.org/), ICANN and PRIVATE sections, rules in punycode.',
    '// The list is subject to the Mozilla Public License, v. 2.0 (https://mozilla.org/MPL/2.0/).',
    `export const PSL_INFO = Object.freeze(${JSON.stringify(info)});`,
    `export const PSL_RULES = ${JSON.stringify(rules.join(' '))};`,
    '',
  ].join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const code = generate(await readFile(DAT_PATH));
  if (check) {
    let current = '';
    try {
      current = await readFile(OUT_PATH, 'utf8');
    } catch {
      current = '';
    }
    if (current !== code) {
      console.error('src/lib/psl-data.js is stale or was edited by hand: run node scripts/psl/make-psl.mjs');
      process.exit(1);
    }
    console.log('src/lib/psl-data.js is up to date');
    return;
  }
  await writeFile(OUT_PATH, code);
  console.log(`wrote ${path.relative(process.cwd(), OUT_PATH)} (${code.length} bytes)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((e) => {
    console.error(e.message || e);
    process.exit(1);
  });
}
